      <span class="spacer" />
      <button class="noprint" title="В окне печати выберите принтер «Сохранить как PDF»" @click="print">Скачать PDF / печать</button>
      <router-link v-if="!session.username" class="noprint" to="/login">Войти в стенд</router-link>
    </div>
    <p class="lead">
      Стенд проверяет платы NAPI-C (память, сеть, SD-NAND) и записывает на SD-NAND операционную систему. Всё делается в
      браузере, командная строка не нужна. Адрес стенда: <b class="mono">{{ server }}</b>
    </p>

    <section>
      <h3><span class="n">1</span> Что нужно</h3>
      <ul>
        <li>Компьютер с Windows, balenaEtcher и кардридер.</li>
        <li>Тестовые microSD от 8 ГБ, по одной на каждую плату, которая проверяется одновременно.</li>
        <li>Платы NAPI-C, кабели Ethernet в сеть стенда, блоки питания.</li>
      </ul>
    </section>

    <section>
      <h3><span class="n">2</span> Подготовить тестовые microSD <small>(один раз)</small></h3>
      <ol>
        <li>Нажмите <b>«Скачать образ microSD»</b> ниже (пароль не нужен). Тот же файл есть в стенде на странице
          «microSD».</li>
        <li>Прошейте скачанный файл на карту через balenaEtcher. Распаковывать файл не нужно.</li>
        <li>Сначала проверьте одну карту: вставьте её в плату (шаг 3). Если плата появилась на стенде, прошейте тем же
          файлом остальные карты.</li>
      </ol>
      <div class="noprint dl">
        <a v-if="status?.sd_image" class="download" :href="links.sdDownload" :download="status.sd_image.file">Скачать образ microSD</a>
        <span v-if="status?.sd_image" class="muted">
          {{ status.sd_image.file }} · {{ formatBytes(status.sd_image.size) }} · собран {{ formatDateTime(status.sd_image.built_at) }}
        </span>
        <span v-else-if="status" class="muted">Образ ещё не собран на стенде.</span>
      </div>
      <p class="hint">
        После обновлений стенда карты перешивать не нужно: программа на них обновляется сама. Перешить карту нужно,
        только если она сломалась или её содержимое испорчено.
      </p>
    </section>

    <section>
      <h3><span class="n">3</span> Подключить платы</h3>
      <ol>
        <li>Вставьте тестовую microSD в плату.</li>
        <li>Подключите Ethernet, затем питание. <b>NAPI-C подключайте кабелем в её собственный разъём Ethernet</b>,
          иначе стенд примет её за NAPI-P и не проверит сеть. <b>NAPI-P</b> подключается через USB-Ethernet адаптер
          (у неё Ethernet на штырях).</li>
        <li>Через 1–2 минуты плата появится на главной странице стенда синим квадратом «готов».</li>
      </ol>
      <p class="hint">
        Тип платы (NAPI-C или NAPI-P) стенд определяет сам по подключению и пишет на квадрате:
        <b>зелёным</b> — распознан, <b>жёлтым «тип ?»</b> — не распознан, <b>жёлтым со значком ✎</b> — задан вручную.
        Вверху стенд пишет, распознан ли тип у всех плат. У NAPI-P сеть не проверяется. Если тип определился неверно,
        выделите квадрат и в панели выберите «Тип платы» или перед запуском выберите «Тип плат в партии»; в подсказке
        остаётся, что определил стенд. Если NAPI-C подключена через USB-адаптер, стенд предупредит: сеть проверится
        через адаптер, а не через порт платы. На квадрате также
        видны IP и MAC платы. У NAPI-P MAC принадлежит USB-адаптеру: если переставить адаптер на другую плату, MAC
        и IP переходят вместе с ним, а номер платы на стенде будет новый.
      </p>
      <p class="hint">
        Платы, которые сняли со стенда, остаются квадратами «нет связи». Кнопка
        <b>«Скрыть офлайн, обнаружить онлайн платы»</b> убирает их (итоги остаются в истории) и заново опрашивает
        подключённые платы. То же происходит само, если уменьшить число в поле «Плат на стенде», а плат на связи
        хватает. Плату с незаконченным заданием кнопка не убирает: сначала выделите её и нажмите
        «Остановить». Платы без связи в партию не берутся: стенд назовёт их номера.
      </p>
      <p class="hint">
        Новая карта при первом включении дольше готовится: около 3 минут. Затем она скачивает с сервера образы ОС
        (несколько минут). Пока образа нет на карте, стенд не даст запустить прошивку и напишет, каких плат это касается.
      </p>
    </section>

    <section>
      <h3><span class="n">4</span> Запустить проверку</h3>
      <ol>
        <li>В поле <b>«Плат на стенде»</b> введите, сколько плат вы подключили. Стенд покажет, если какая-то не появилась.</li>
        <li>Нажмите <b>«Выбрать все онлайн»</b> или щёлкните по нужным квадратам: щелчок выбирает плату или снимает
          выбор, Shift+щелчок — все подряд. У выбранной платы толстая синяя обводка и синий кружок с ✓. Если ничего
          не выбрать, стенд предложит запустить на всех свободных платах на связи. После запуска выбор снимается;
          платы, где задание уже идёт, в новую партию не попадают — можно выбирать следующие, пока идут тесты.</li>
        <li>В списке <b>«ОС для внутреннего накопителя»</b> оставьте выбранное по умолчанию (Armbian), если не сказано
          иное.</li>
        <li>Нажмите нужную кнопку:
          <ul>
            <li><b>«Тесты + прошивка»</b> — обычный режим: проверка и запись ОС;</li>
            <li><b>«Только тесты»</b> — проверка без записи;</li>
            <li><b>«Только прошивка»</b> — запись ОС на уже проверенные платы.</li>
          </ul>
        </li>
        <li>Подтвердите в окне. Квадраты станут жёлтыми, полоска под номером показывает, что идёт: RAM, NET, NAND
          (внутренняя SD-NAND), FLASH, CHECKB. Внизу квадрата — «осталось ~N мин», вверху стенда — когда закончится
          партия и <b>☕ на сколько можно отойти</b>: до первой платы, которой нужен человек (вынуть microSD для
          проверки загрузки), или до конца партии.</li>
      </ol>
      <p class="hint">
        Если не прошла только сеть, итог — <b>WARN</b> (рыжий квадрат), а не FAIL: чаще виновата сеть стенда, а не
        плата. В «Тесты + прошивка» такая плата всё равно прошивается, на квадрате «· прошита». FAIL памяти
        или SD-NAND прошивку останавливает. «Только прошивка» тоже принимает плату, у которой не прошла только сеть. Если сеть стенда временно плохая (например, Wi-Fi до сервера), поставьте
        галочку <b>«Без проверки сети»</b>: NET будет «пропущен», это записывается в историю.
      </p>
      <p class="hint">
        Если при входе стенд пишет «Осторожно: идут тесты», на стенде уже работает другой человек. Не выбирайте его
        платы и не нажимайте «Остановить» без выделения: это остановит его партию.
      </p>
    </section>

    <section>
      <h3><span class="n">5</span> Проверка загрузки (CHECKB)</h3>
      <p>
        После прошивки квадрат станет жёлтым с надписью <b>«ожидание загрузки»</b>. Тогда:
        <b>выключите плату, выньте microSD, включите плату.</b> Плата загрузится с SD-NAND, и стенд сам это увидит
        (до 10 минут). MicroSD больше не вставляйте в эту плату, карта нужна для следующей. У NAPI-P USB-адаптер
        не отключайте: плату ищут в сети по нему.
      </p>
      <p class="hint">
        Стенд видит загрузку, только если плата в одной сети с сервером стенда. Если плата получила
        адрес из другой сети (за роутером), проверка загрузки сразу пропускается: квадрат станет <b>оранжевым</b>
        «PASS, загрузка не подтверждена — проверьте», и загрузку нужно проверить вручную.
      </p>
      <p class="hint">
        Не успели вынуть microSD, и квадрат стал оранжевым? Выделите такие платы (или ничего не выделяйте — стенд
        предложит все с неподтверждённой загрузкой) и нажмите <b>«Только BOOTCHECK»</b>: стенд снова ждёт загрузку
        до 10 минут. Выключите плату, выньте microSD и включите.
      </p>
      <p class="hint">
        Если проверка загрузки не нужна, перед запуском поставьте галочку «Не проверять загрузку с SD-NAND (BOOTCHECK)».
      </p>
    </section>

